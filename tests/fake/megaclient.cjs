#!/usr/bin/env node
// A stand-in for MEGAcmd's client (MegaClient.exe / mega-exec), for the tests. It answers the commands the plugin uses
// with output in MEGAcmd 2.x's formats (src/megacmdexecuter.cpp, src/sync_command.cpp) and MEGAcmd's exit codes.
//
//   FAKE_MEGACMD_STATE  a JSON file with the fake's state (read, and written back after a change)
//   FAKE_MEGACMD_CALLS  a file to which each call's argument array is appended, one JSON line per call
//
// State: { loggedIn, email, version, syncs: [{id, local, remote, runState, status, error, size, files, dirs}],
//          folders: { "/RAG": ["a.md", ...] }, transfers: {downloads, downloaded, downloadTotal, downloadPct, uploads,
//          uploaded, uploadTotal, uploadPct}, issues: [{id, sync, reason}], hang: "command name", nextId }
"use strict";
const fs = require("fs");

const args = process.argv.slice(2);
const statePath = process.env.FAKE_MEGACMD_STATE;
const callsPath = process.env.FAKE_MEGACMD_CALLS;
if (callsPath) fs.appendFileSync(callsPath, JSON.stringify(args) + "\n");
// MEGAcmd's server writes sign-in commands unredacted when this is set where it starts: the plugin must never pass it.
if (callsPath && process.env.MEGACMD_DO_NOT_REDACT_LINES !== undefined) fs.appendFileSync(callsPath, JSON.stringify(["ENV:MEGACMD_DO_NOT_REDACT_LINES"]) + "\n");
const state = statePath && fs.existsSync(statePath) ? JSON.parse(fs.readFileSync(statePath, "utf8")) : {};
const save = () => statePath && fs.writeFileSync(statePath, JSON.stringify(state, null, 1));

const out = (s) => process.stdout.write(s + "\n");
const err = (s) => process.stderr.write(s + "\n");
const exit = (code) => process.exit(code);
const EARGS = 51, NOTFOUND = 53, NOTLOGGEDIN = 57, EXISTS = 64;

const cmd = args[0];
const opts = {};
const words = [];
const flags = new Set();
for (const a of args.slice(1)) {
  const m = /^--([^=]+)=(.*)$/.exec(a);
  if (m) opts[m[1]] = m[2];
  else if (/^--?[A-Za-z]/.test(a)) flags.add(a.replace(/^-+/, ""));
  else words.push(a);
}

if (state.hang === cmd) setTimeout(() => exit(0), 600_000);
else main();

function table(cols, rows) {
  const sep = opts["col-separator"];
  const wanted = opts["output-cols"] ? opts["output-cols"].split(",").filter((c) => cols.includes(c)) : cols;
  if (sep) {
    out(wanted.join(sep));
    for (const r of rows) out(wanted.map((c) => r[c]).join(sep));
  } else {
    out(wanted.join(" "));
    for (const r of rows) out(wanted.map((c) => r[c]).join("  "));
  }
}

function syncRow(s) {
  return {
    ID: s.id,
    LOCALPATH: "\\\\?\\" + s.local,
    REMOTEPATH: s.remote,
    RUN_STATE: s.runState || "Running",
    STATUS: s.status || "Synced",
    ERROR: s.error || "NO",
    SIZE: s.size || "0.00  B",
    FILES: String(s.files ?? 0),
    DIRS: String(s.dirs ?? 0),
  };
}

// `login <email> <password> [--auth-code=…]`, as MEGAcmd's server answers it (src/megacmdexecuter.cpp): already
// signed in (54), wrong email or password (9), unconfirmed account (13), two-factor code asked on the client's input
// when the account has one and no --auth-code was given (a wrong code: 5). The account is state.account:
// { email, password, mfa: "123456" | undefined, unconfirmed: bool, blocked: "reason" | undefined, tooMany: bool,
//   slow: ms }. The question and messages are MEGAcmd's own (src/megacmdexecuter.cpp, read 2026-10-29).
function login() {
  if (state.loggedIn) {
    err("[err: ] Already logged in. Please log out first.");
    return exit(54);
  }
  if (words.length === 1) {
    err("[err: ] Extra args required in non-interactive mode. Usage: login [--auth-code=XXXX] email password");
    return exit(EARGS);
  }
  const acc = state.account || {};
  const [email, password] = words;
  const finish = (pin) => {
    if (email !== acc.email || password !== acc.password) {
      err("[err: ] Login failed: invalid email or password");
      return exit(9);
    }
    if (acc.mfa !== undefined && pin !== acc.mfa) {
      err("[err: ] Login failed: incorrect authentication");
      return exit(5);
    }
    if (acc.blocked) {
      // MEGAcmd: checkNoErrors(error, "Login") with the reason MEGA gave (src/listeners.cpp, EVENT_ACCOUNT_BLOCKED)
      err(`[err: ] Failed to Login: Account blocked.Reason: ${acc.blocked}`);
      return exit(16);
    }
    if (acc.tooMany) {
      err("[err: ] Failed to Login: Too many requests for this resource");
      return exit(6);
    }
    if (acc.unconfirmed) {
      err("[err: ] Login failed: unconfirmed account. Please confirm your account");
      return exit(13);
    }
    state.loggedIn = true;
    state.email = email;
    save();
    return exit(0);
  };
  const go = () => {
    if (acc.mfa !== undefined && email === acc.email && password === acc.password && opts["auth-code"] === undefined) {
      process.stdout.write("Enter the code generated by your authentication app:  ");
      let buf = "";
      process.stdin.setEncoding("utf8");
      process.stdin.on("data", (d) => {
        buf += d;
        const nl = buf.indexOf("\n");
        if (nl >= 0) finish(buf.slice(0, nl).trim());
      });
      process.stdin.on("end", () => finish(buf.trim()));
      return;
    }
    finish(opts["auth-code"]);
  };
  if (acc.slow) setTimeout(go, acc.slow);
  else go();
}

function needLogin() {
  if (!state.loggedIn) {
    err("[err: ] Not logged in");
    exit(NOTLOGGEDIN);
  }
}

function main() {
  switch (cmd) {
    case "version":
      out(`MEGAcmd version: ${state.version || "2.1.1.0"}: code 2010100`);
      return exit(0);
    case "whoami":
      needLogin();
      out(`Account e-mail: ${state.email}`);
      return exit(0);
    case "quit":
      out("closing application ...");
      return exit(0);
    case "login":
      return login();
    case "sync": {
      needLogin();
      const syncs = state.syncs || (state.syncs = []);
      const pause = flags.has("p") || flags.has("pause");
      const enable = flags.has("e") || flags.has("enable");
      const del = flags.has("d") || flags.has("delete");
      if ([pause, enable, del].filter(Boolean).length > 1) {
        err("Only one action (disable, enable, or remove) can be specified at a time");
        return exit(EARGS);
      }
      if (words.length === 2) {
        const [local, remote] = words;
        if (!(state.folders || {})[remote]) {
          err(`Remote directory ${remote} does not exist`);
          return exit(NOTFOUND);
        }
        if (syncs.some((s) => s.local.toLowerCase() === local.toLowerCase())) {
          err(`Failed to sync ${local} to ${remote}: Active sync same path`);
          return exit(EXISTS);
        }
        const id = state.nextId || "AbCdEfGh123";
        syncs.push({ id, local, remote, runState: "Running", status: "Syncing", error: "NO", size: "0.00  B", files: 0, dirs: 0 });
        save();
        out(`Added sync: \\\\?\\${local} to ${remote}`);
        return exit(0);
      }
      if (words.length === 1) {
        const s = syncs.find((x) => x.id === words[0] || x.local === words[0]);
        if (!s) {
          err(`Sync not found: ${words[0]}`);
          return exit(NOTFOUND);
        }
        if (del) {
          state.syncs = syncs.filter((x) => x !== s);
          save();
          out(`Sync removed: \\\\?\\${s.local} to ${s.remote}`);
          return exit(0);
        }
        if (pause) s.runState = "Disabled";
        if (enable) s.runState = "Running";
        save();
        if (pause || enable) out(`Sync ${pause ? "paused" : "enabled"}: \\\\?\\${s.local} to ${s.remote}`);
        table(["ID", "LOCALPATH", "REMOTEPATH", "RUN_STATE", "STATUS", "ERROR", "SIZE", "FILES", "DIRS"], [syncRow(s)]);
        return exit(0);
      }
      if (words.length === 0) {
        table(["ID", "LOCALPATH", "REMOTEPATH", "RUN_STATE", "STATUS", "ERROR", "SIZE", "FILES", "DIRS"], syncs.map(syncRow));
        if ((state.issues || []).length) {
          out("");
          err('You have sync issues. Use the "sync-issues" command to display them.');
        }
        return exit(0);
      }
      err("Usage: sync [localpath dstremotepath| [-dpe] [ID|localpath]");
      return exit(EARGS);
    }
    case "ls": {
      needLogin();
      const items = (state.folders || {})[words[0]];
      if (!items) {
        err(`Couldn't find ${words[0]}`);
        return exit(NOTFOUND);
      }
      for (const i of items) out(i);
      return exit(0);
    }
    case "mkdir": {
      needLogin();
      state.folders = state.folders || {};
      if (state.folders[words[0]] && !flags.has("p")) {
        err(`Folder already exists: ${words[0]}`);
        return exit(EXISTS);
      }
      state.folders[words[0]] = state.folders[words[0]] || [];
      save();
      return exit(0);
    }
    case "logout": {
      // `logout` (src/megacmdexecuter.cpp): "Logging out..."; the session, its cache and its syncs are deleted.
      needLogin();
      out("Logging out...");
      if (state.logoutFails) {
        err("[err: ] Failed to logout: Request failed, retrying");
        return exit(59);
      }
      state.loggedIn = false;
      state.syncs = [];
      save();
      return exit(0);
    }
    case "transfers": {
      needLogin();
      if (flags.has("c") && flags.has("a")) {
        // `transfers -c -a` cancels only transfers that are not a sync's (MEGA SDK cancelTransfers: "Marked all
        // non-sync non-streaming transfers as cancelled"); a sync's stay listed (and counted by --summary).
        const rows = state.transferRows || [];
        if (!state.stuckTransfers) state.transferRows = rows.filter((r) => r.sync);
        if (!state.stuckTransfers && !rows.some((r) => r.sync)) state.transfers = undefined;
        save();
        out("Download transfers cancelled successfully.");
        out("Upload transfers cancelled successfully.");
        return exit(0);
      }
      const t = state.transfers || { downloads: 0, downloaded: "0.00  B", downloadTotal: "0.00  B", downloadPct: "0.00", uploads: 0, uploaded: "0.00  B", uploadTotal: "0.00  B", uploadPct: "0.00" };
      if (flags.has("summary")) {
        const f = (s, n) => String(s).padStart(n);
        out(`${f("NUM DOWNLOADS", 16)}${f("DOWNLOADED", 12)}${f("TOTAL", 12)}${f("%   ", 8)}     ${f("NUM UPLOADS", 16)}${f("UPLOADED", 12)}${f("TOTAL", 12)}${f("%   ", 8)}`);
        out(`${f(t.downloads, 16)}${f(t.downloaded, 12)}${f(t.downloadTotal, 12)}${f(t.downloadPct + "%", 8)}     ${f(t.uploads, 16)}${f(t.uploaded, 12)}${f(t.uploadTotal, 12)}${f(t.uploadPct + "%", 8)}`);
        return exit(0);
      }
      // The list: a sync's transfers only with --show-syncs (src/megacmdexecuter.cpp); completed ones are not listed.
      const rows = (state.transferRows || []).filter((r) => flags.has("show-syncs") || !r.sync);
      const limit = Number(opts.limit || 10);
      table(
        ["TYPE", "TAG", "SOURCEPATH", "DESTINYPATH", "PROGRESS", "STATE"],
        rows.slice(0, limit).map((r, i) => ({ TYPE: r.sync ? "⇵" : "⇑", TAG: String(r.tag ?? 1000 + i), SOURCEPATH: r.source || "C:\\v\\note.md", DESTINYPATH: r.destination || "/RAG/", PROGRESS: r.progress || "10.00%", STATE: r.state || "ACTIVE" })),
      );
      return exit(0);
    }
    case "sync-issues": {
      needLogin();
      const issues = state.issues || [];
      if (!issues.length) {
        out("There are no sync issues");
        return exit(0);
      }
      table(["ISSUE_ID", "PARENT_SYNC", "REASON"], issues.map((i) => ({ ISSUE_ID: i.id, PARENT_SYNC: i.sync, REASON: i.reason })));
      return exit(0);
    }
    default:
      err(`Command not found: ${cmd}`);
      return exit(EARGS);
  }
}
